# helper function to parse a single embedding cell into a list of floats
def parse_embedding(val):
    # if the value is None, return None
    if val is None:
        return None
    # if the value is already a list/tuple/ndarray, try to cast to floats
    if isinstance(val, (list, tuple, np.ndarray)):
        try:
            return [float(x) for x in val]
        except (TypeError, ValueError):
            return None
    # if the value is not a string, give up
    if not isinstance(val, str):
        return None
    # strip the string
    s = val.strip()
    # if the string is empty, return None
    if not s:
        return None
    # try JSON first (fastest), then literal_eval as fallback
    try:
        parsed = json.loads(s)
    except (json.JSONDecodeError, ValueError):
        try:
            parsed = ast.literal_eval(s)
        except (ValueError, SyntaxError):
            return None
    # if the parsed value is not a list/tuple, return None
    if not isinstance(parsed, (list, tuple)):
        return None
    # try to cast every element to float
    try:
        return [float(x) for x in parsed]
    except (TypeError, ValueError):
        return None

# helper function to build a feature DataFrame with text + per-dim embedding columns
def build_feature_frame(df, text_col, embedding_col):
    # parse every cell in the embedding column
    parsed = df[embedding_col].apply(parse_embedding)
    # find the rows where parsing succeeded
    valid_mask = parsed.notna()
    # count how many rows failed to parse
    dropped_parse = (~valid_mask).sum()
    # report the number of dropped rows
    if dropped_parse:
        print(f"Dropped {dropped_parse} rows: unparseable '{embedding_col}'")
    # keep only the valid rows
    df = df.loc[valid_mask].copy()
    # keep the parsed embeddings aligned with the kept rows
    parsed = parsed.loc[valid_mask]

    # find the dominant embedding length and keep only rows matching it
    lengths = parsed.apply(len)
    # if no embeddings remain, raise an error
    if lengths.empty:
        raise ValueError(
            f"No valid embeddings found in column '{embedding_col}'. "
            f"Check the CSV format."
        )
    # find the most common embedding length
    dom_len = int(lengths.mode().iloc[0])
    # find the rows with a different length
    bad_len_mask = lengths != dom_len
    # if there are any rows with a different length, drop them
    if bad_len_mask.any():
        print(f"Dropped {bad_len_mask.sum()} rows: embedding length != {dom_len}")
        df = df.loc[~bad_len_mask].copy()
        parsed = parsed.loc[~bad_len_mask]

    # build the embedding matrix
    emb_matrix = np.asarray(parsed.tolist(), dtype=np.float32)
    # build the embedding column names
    emb_cols = [f"emb_{i:04d}" for i in range(dom_len)]
    # build the embedding DataFrame
    emb_df = pd.DataFrame(emb_matrix, columns=emb_cols, index=df.index)

    # concatenate the text column and the embedding columns
    out = pd.concat(
        [df[text_col].astype(str).rename(text_col), emb_df],
        axis=1,
    )
    # return the feature frame, the embedding column names, and the embedding dimension
    return out, emb_cols, dom_len
