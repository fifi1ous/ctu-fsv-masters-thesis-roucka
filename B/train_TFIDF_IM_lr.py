# helper function to save the feature importance
def save_feature_importance(pipeline, out_dir, top_k=25):
    # get the feature names from the ColumnTransformer
    feat_names = get_feature_names_from_ct(pipeline)
    # try to get the classifier
    try:
        clf = pipeline.named_steps["clf"]
    # if the classifier is not found, return
    except (KeyError, AttributeError):
        return
    # if the feature names or classifier coefficients are missing, return
    if feat_names is None or not hasattr(clf, "coef_"):
        return

    # get the coefficients
    coef = clf.coef_
    # get the classes
    classes = clf.classes_
    # if the feature-name and coef shapes do not match, warn and return
    if coef.shape[1] != len(feat_names):
        print(f"[warn] feature-name/coef shape mismatch: "
              f"{len(feat_names)} vs {coef.shape[1]} -- skipping importance")
        return

    # class list for the output DataFrame
    class_list = classes

    # create a list to store the feature importance
    rows = []
    # iterate over the classes
    for i, cls in enumerate(class_list):
        # if the coefficients are for a binary classification, set the row index to 0
        row_idx = 0 if coef.shape[0] == 1 else i
        # get the coefficients for the current class
        c = coef[row_idx]
        # get the top k features
        top_pos = np.argsort(c)[-top_k:][::-1]
        # iterate over the top k features
        for rank, idx in enumerate(top_pos):
            # add the feature importance to the list
            rows.append({
                "class": cls, "rank": rank + 1,
                "feature": feat_names[idx], "coef": float(c[idx]),
            })
    # convert the list to a pandas DataFrame
    pd.DataFrame(rows).to_csv(out_dir / "feature_importance_best.csv", index=False)

# helper function to build the pipeline
def make_pipeline(text_col, emb_cols, *, tfidf_kwargs=None, clf_kwargs=None):
    # default to empty kwargs if none are provided
    tfidf_kwargs = tfidf_kwargs or {}
    clf_kwargs = clf_kwargs or {}

    # text branch: TfidfVectorizer
    text_branch = Pipeline([
        ("tfidf", TfidfVectorizer(**tfidf_kwargs)),
    ])
    # embedding branch: StandardScaler keeps embedding scale comparable to L2-normalised TF-IDF
    emb_branch = Pipeline([
        ("scaler", StandardScaler(with_mean=True)),
    ])

    # combine the two branches in a ColumnTransformer
    features = ColumnTransformer(
        transformers=[
            ("text", text_branch, text_col),
            ("emb",  emb_branch,  emb_cols),
        ],
        sparse_threshold=0.3,
    )

    # final pipeline: ColumnTransformer -> LogisticRegression
    return Pipeline([
        ("features", features),
        ("clf", LogisticRegression(**clf_kwargs)),
    ])

