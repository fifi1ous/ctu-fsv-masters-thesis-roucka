# helper function to extract feature names from a ColumnTransformer pipeline
def get_feature_names_from_ct(pipeline):
    # try to get the ColumnTransformer step named 'features'
    try:
        ct = pipeline.named_steps["features"]
    # if the ColumnTransformer is not found, return None
    except (KeyError, AttributeError):
        return None
    # create a list to store the feature names
    names = []
    # try to collect feature names from both branches
    try:
        # text branch: TfidfVectorizer inside a sub-pipeline called 'text'
        text_branch = dict(ct.named_transformers_).get("text")
        # if the text branch exists, get its tfidf step
        if text_branch is not None:
            # if the text branch is a pipeline, get the tfidf step from it
            if hasattr(text_branch, "named_steps"):
                tfidf = text_branch.named_steps.get("tfidf")
            # otherwise the branch itself is the tfidf
            else:
                tfidf = text_branch
            # if the tfidf is found, extend the names list with prefixed feature names
            if tfidf is not None and hasattr(tfidf, "get_feature_names_out"):
                names.extend(
                    [f"text::{n}" for n in tfidf.get_feature_names_out()]
                )
        # embedding branch: just the raw column names, prefixed
        emb_cols = getattr(ct, "transformers_", [])
        # iterate over the transformers
        for name, _trans, cols in emb_cols:
            # if the branch is the embedding branch, extend the names list
            if name == "emb" and cols is not None:
                names.extend([f"emb::{c}" for c in cols])
    # if anything goes wrong, warn and return None
    except Exception as e:
        print(f"[warn] could not collect feature names: {e}")
        return None
    # return the names array, or None if empty
    return np.asarray(names) if names else None
