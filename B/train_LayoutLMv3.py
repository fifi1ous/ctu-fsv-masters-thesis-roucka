# helper function to compute classification metrics for the Trainer
def compute_metrics(eval_pred):
    # unpack the logits and labels
    logits, labels = eval_pred
    # take the argmax over classes to get predictions
    preds = np.argmax(logits, axis=-1)
    # compute macro precision, recall, and f1
    precision, recall, f1_macro, _ = precision_recall_fscore_support(
        labels, preds, average="macro", zero_division=0
    )
    # return the full metric dictionary
    return {
        "accuracy": accuracy_score(labels, preds),
        "f1_macro": f1_macro,
        "f1_weighted": f1_score(labels, preds, average="weighted", zero_division=0),
        "precision_macro": precision,
        "recall_macro": recall,
    }

