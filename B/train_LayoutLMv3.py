# // this part of code was modified by Claude 4.7 opus model //
class LayoutLMv3DocClassDataset(torch.utils.data.Dataset):
    # initialize the dataset
    def __init__(self, manifest, label2id, processor, dataset_root, max_length=512):
        # store the manifest list
        self.manifest = manifest
        # store the label-to-id mapping
        self.label2id = label2id
        # store the processor
        self.processor = processor
        # resolve and store the dataset root
        self.dataset_root = Path(dataset_root).resolve()
        # store the max sequence length
        self.max_length = max_length

    # return the number of examples
    def __len__(self):
        return len(self.manifest)

    # encode and return a single example by index
    def __getitem__(self, idx):
        # get the manifest entry
        m = self.manifest[idx]
        # get the image path
        img_path = Path(m["image_path"])
        # if the image path is relative, prepend the dataset root
        if not img_path.is_absolute():
            img_path = self.dataset_root / img_path
        # load the image and convert to RGB
        image = Image.open(img_path).convert("RGB")

        # encode the image, words, and boxes with the processor
        encoded = self.processor(
            image,
            text=m["words"],
            boxes=m["boxes"],
            truncation=True,
            padding="max_length",
            max_length=self.max_length,
            return_tensors="pt",
        )
        # squeeze the batch dimension off every tensor
        item = {k: v.squeeze(0) for k, v in encoded.items()}
        # add the label as a long tensor
        item["labels"] = torch.tensor(self.label2id[m["label"]], dtype=torch.long)
        # return the encoded example
        return item
