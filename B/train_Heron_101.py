# helper function to atomically save the best model
def _atomic_save_best(metrics, epoch):
    # build the final and tmp directories
    final_dir = output_dir / "final"
    tmp_dir = output_dir / "final.tmp"
    # remove any leftover tmp dir
    if tmp_dir.exists():
        shutil.rmtree(tmp_dir)
    # create the tmp dir
    tmp_dir.mkdir(parents=True)

    # save the model and processor to the tmp dir
    model.save_pretrained(tmp_dir)
    image_processor.save_pretrained(tmp_dir)
    # save the eval metrics
    with open(tmp_dir / "eval_metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics | {"epoch": epoch}, f, indent=2)

    # atomically swap the tmp dir into place
    if final_dir.exists():
        shutil.rmtree(final_dir)
    os.rename(tmp_dir, final_dir)
    # return the final path
    return final_dir

# Trainer callback that runs COCO eval at the end of every Nth epoch
class EvalCallback(TrainerCallback):
    # called by the Trainer at the end of each epoch
    def on_epoch_end(self, cbargs, state, control, **kwargs):
        # get the integer epoch
        epoch = int(state.epoch or 0)
        # skip if this isn't an eval epoch
        if epoch == 0 or epoch % args.eval_every != 0:
            return
        # run the manual eval
        print(f"\n[eval] Running COCO eval on val set at epoch {epoch} ...")
        metrics = evaluate_model(
            model, image_processor, val_ds,
            batch_size=args.batch_size, device=device,
            return_predictions=False,
        )
        print(f"[eval] {metrics}")
        # log to Trainer state so it shows up in logs
        if state.log_history is not None:
            state.log_history.append(
                {f"eval/{k}": v for k, v in metrics.items()} | {"epoch": epoch}
            )

        # save best model atomically if this beats the running best mAP
        if metrics["map"] > best_map["value"]:
            best_map["value"] = metrics["map"]
            best_map["epoch"] = epoch
            best_map["evals_since_best"] = 0
            best_dir = _atomic_save_best(metrics, epoch)
            print(f"[eval] New best mAP={metrics['map']:.4f} saved to {best_dir}")
        # otherwise bump the patience counter and possibly early-stop
        else:
            best_map["evals_since_best"] += 1
            print(f"[eval] No improvement ({best_map['evals_since_best']}/{args.patience} evals "
                  f"since best mAP={best_map['value']:.4f} at epoch {best_map['epoch']})")
            if best_map["evals_since_best"] >= args.patience:
                print(f"[eval] EARLY STOPPING: val mAP plateaued for {args.patience} evals")
                control.should_training_stop = True

# attach the eval callback to the Trainer
