# COCO-format detection dataset; emits dicts in the shape RT-DETR's image processor expects
# // this part of code was modified by Claude 4.7 opus model //
class CocoDetectionDataset(Dataset):
    # initialize the dataset
    def __init__(self, ann_file, img_dir, transform):
        # load the COCO annotations
        self.coco = COCO(str(ann_file))
        # store the image directory
        self.img_dir = Path(img_dir)
        # store the augmentation pipeline
        self.transform = transform
        # store the sorted image ids for deterministic ordering
        self.ids = sorted(self.coco.imgs.keys())

    # return the number of images
    def __len__(self):
        return len(self.ids)

    # load and augment a single example
    def __getitem__(self, idx):
        # get the image id
        img_id = self.ids[idx]
        # get the image info dict
        info = self.coco.imgs[img_id]
        # build the image path
        img_path = self.img_dir / info["file_name"]
        # load the image as a numpy array
        image = np.array(Image.open(img_path).convert("RGB"))

        # get the annotation ids for this image
        ann_ids = self.coco.getAnnIds(imgIds=img_id)
        # load the annotations
        anns = self.coco.loadAnns(ann_ids)

        # extract the bboxes (COCO [x, y, w, h])
        bboxes = [a["bbox"] for a in anns]
        # extract the category ids
        labels = [a["category_id"] for a in anns]

        # apply the augmentation pipeline if provided
        if self.transform is not None:
            out = self.transform(image=image, bboxes=bboxes, category=labels)
            image = out["image"]
            bboxes = out["bboxes"]
            labels = out["category"]

        # rebuild COCO-style annotations for the image processor
        formatted = []
        # iterate over the bboxes and labels
        for bbox, cat in zip(bboxes, labels):
            # unpack the bbox
            x, y, w, h = bbox
            # append the formatted annotation
            formatted.append({
                "image_id": img_id,
                "category_id": int(cat),
                "bbox": [float(x), float(y), float(w), float(h)],
                "area": float(w * h),
                "iscrowd": 0,
            })

        # return the dict expected by the image processor
        return {
            "image_id": img_id,
            "image": image,
            "annotations": formatted,
        }

# helper function to build the augmentation pipeline (separate train/val branches)
def build_transforms(image_size, train):
    # training: moderate geometric + color aug, bbox handling done by albumentations in COCO format
    if train:
        return A.Compose(
            [
                A.LongestMaxSize(max_size=image_size),
                A.PadIfNeeded(
                    min_height=image_size,
                    min_width=image_size,
                    border_mode=0,  # constant black
                ),
                A.HorizontalFlip(p=0.5),
                A.RandomBrightnessContrast(p=0.3),
                A.HueSaturationValue(
                    hue_shift_limit=5, sat_shift_limit=10, val_shift_limit=10, p=0.3
                ),
                A.GaussNoise(p=0.2),
            ],
            bbox_params=A.BboxParams(
                format="coco",
                label_fields=["category"],
                min_area=4,           # tiny floor; we don't want to drop small BPEJ/ss boxes
                min_visibility=0.3,   # drop boxes that get mostly cropped (>70% lost)
            ),
        )
    # validation: just LongestMaxSize + PadIfNeeded to preserve aspect ratio
    else:
        return A.Compose(
            [
                A.LongestMaxSize(max_size=image_size),
                A.PadIfNeeded(
                    min_height=image_size, min_width=image_size, border_mode=0
                ),
            ],
            bbox_params=A.BboxParams(format="coco", label_fields=["category"]),
        )

# collator: converts a batch of Dataset items to model inputs via the image processor
@dataclass
class DetrCollator:
    # the image processor
    image_processor: Any

    # collate a batch
    def __call__(self, batch):
        # extract images
        images = [ex["image"] for ex in batch]
        # extract annotations
        annotations = [
            {"image_id": ex["image_id"], "annotations": ex["annotations"]}
            for ex in batch
        ]
        # encode with the processor
        encoded = self.image_processor(
            images=images,
            annotations=annotations,
            return_tensors="pt",
        )
        # return the encoded batch
        return encoded

# stateful COCO mAP evaluator; accumulates predictions across the eval run
class CocoMapEvaluator:
    # initialize the evaluator
    def __init__(self, coco_gt, id2label):
        # store the ground-truth COCO object
        self.coco_gt = coco_gt
        # store the id-to-label mapping
        self.id2label = id2label
        # reset the results list
        self.reset()

    # reset the accumulated predictions
    def reset(self):
        self.results = []

    # add a batch of predictions
    def update(self, image_ids, predictions):
        # iterate over each image's predictions
        for img_id, pred in zip(image_ids, predictions):
            # extract boxes (xyxy in original image coords)
            boxes = pred["boxes"].tolist()
            # extract scores
            scores = pred["scores"].tolist()
            # extract labels
            labels = pred["labels"].tolist()
            # convert each prediction to COCO result format
            for (x1, y1, x2, y2), s, l in zip(boxes, scores, labels):
                self.results.append({
                    "image_id": int(img_id),
                    "category_id": int(l),
                    "bbox": [x1, y1, x2 - x1, y2 - y1],
                    "score": float(s),
                })

    # compute the COCO mAP metrics
    def summarize(self):
        # if no predictions, return zeros
        if not self.results:
            return {"map": 0.0, "map_50": 0.0, "map_75": 0.0}
        # load predictions into the COCO API
        coco_dt = self.coco_gt.loadRes(self.results)
        # build the COCO evaluator
        coco_eval = COCOeval(self.coco_gt, coco_dt, "bbox")
        # run evaluate, accumulate, summarize
        coco_eval.evaluate()
        coco_eval.accumulate()
        coco_eval.summarize()
        # extract the 12-element COCO stats array
        stats = coco_eval.stats
        # return the named subset we care about
        return {
            "map":     float(stats[0]),  # AP @ IoU=0.50:0.95
            "map_50":  float(stats[1]),
            "map_75":  float(stats[2]),
            "map_s":   float(stats[3]),
            "map_m":   float(stats[4]),
            "map_l":   float(stats[5]),
            "mar_100": float(stats[8]),
        }

# manual eval loop - computes COCO mAP on a dataset
@torch.no_grad()
def evaluate_model(model, image_processor, dataset, batch_size, device,
                   threshold=0.0, return_predictions=False):
    # set the model to eval mode
    model.eval()
    # build the COCO mAP evaluator
    evaluator = CocoMapEvaluator(dataset.coco, ID2LABEL)
    # optionally collect per-image predictions
    predictions_by_img = {} if return_predictions else None

    # iterate over the val image ids in deterministic order
    img_ids_all = sorted(dataset.coco.imgs.keys())
    # batch the eval loop
    for start in range(0, len(img_ids_all), batch_size):
        # get the batch of image ids
        batch_ids = img_ids_all[start:start + batch_size]
        # collect images and original sizes
        images = []
        sizes = []
        # iterate over the batch
        for img_id in batch_ids:
            # get the image info
            info = dataset.coco.imgs[img_id]
            # load the original image
            img = Image.open(dataset.img_dir / info["file_name"]).convert("RGB")
            # store the image
            images.append(img)
            # store the original (H, W)
            sizes.append((info["height"], info["width"]))

        # build the target_sizes tensor on the same device as the model
        target_sizes = torch.tensor(sizes, device=device)

        # encode the batch with the image processor
        encoded = image_processor(images=images, return_tensors="pt")
        # move the encoded batch to the device
        encoded = {k: v.to(device) for k, v in encoded.items()}
        # run the model forward pass
        outputs = model(**encoded)
        # post-process to original image coords
        results = image_processor.post_process_object_detection(
            outputs, target_sizes=target_sizes, threshold=threshold
        )
        # accumulate into the COCO evaluator
        evaluator.update(batch_ids, results)

        # optionally collect predictions for downstream use
        if return_predictions:
            for img_id, r in zip(batch_ids, results):
                boxes = r["boxes"].tolist()
                scores = r["scores"].tolist()
                labels = r["labels"].tolist()
                predictions_by_img[int(img_id)] = [
                    {
                        "bbox": [x1, y1, x2 - x1, y2 - y1],  # xywh
                        "score": float(s),
                        "label": int(l),
                    }
                    for (x1, y1, x2, y2), s, l in zip(boxes, scores, labels)
                ]

    # compute the final metrics
    metrics = evaluator.summarize()
    # restore train mode
    model.train()
    # return metrics, optionally with predictions
    if return_predictions:
        return metrics, predictions_by_img
    return metrics
